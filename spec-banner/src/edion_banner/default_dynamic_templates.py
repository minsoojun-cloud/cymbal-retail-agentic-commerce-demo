def _box(
    box_id: str,
    box_type: str,
    title: str,
    x: int,
    y: int,
    w: int,
    h: int,
    field_key: str,
    *,
    unit: str | None = None,
    prefix: str | None = None,
    sub_keys: list[str] | None = None,
    show_title_bar: bool = True,
    title_bg: str = "#666666",
    bg_color: str = "#FFFFFF",
    border_color: str = "#999999",
    value_color: str = "#111111",
    font_size: int | str = "auto",
) -> dict[str, Any]:
    return {
        "id": box_id,
        "box_type": box_type,
        "title": title,
        "show_title_bar": show_title_bar,
        "title_bg_color": title_bg,
        "title_text_color": "#FFFFFF",
        "bg_color": bg_color,
        "border_color": border_color,
        "border_width": 1.5,
        "border_radius": 0,
        "x": x,
        "y": y,
        "w": w,
        "h": h,
        "value_font_size": font_size,
        "value_color": value_color,
        "text_align": "center",
        "binding": {
            "field_key": field_key,
            "label_override": title,
            "unit_override": unit,
            "prefix_text": prefix,
            "sub_field_keys": sub_keys or [],
            "empty_fallback": "-",
        },
    }


