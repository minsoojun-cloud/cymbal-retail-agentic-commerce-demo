def infer_category_from_product(
    product_name: str | None,
    class_code: str | None = None,
    features: str | None = None,
    model_no: str | None = None,
) -> str | None:
    text = f"{product_name or ''} {features or ''} {model_no or ''}".upper()
    if any(k in text for k in ["ワインセラー", "ﾜｲﾝｾﾗｰ", "WINE", "IWCP", "SAB-"]):
        return "wine_cellar"
    if any(k in text for k in ["冷温庫", "ﾚｲｵﾝｺ", "VS442", "UL18DBA"]):
        return "cooler_warmer"
    if any(k in text for k in ["冷凍庫", "ﾚｲﾄｳｺ", "ﾌﾘｰｻﾞｰ", "AQFSF", "MFU"]):
        return "freezer"
    if any(k in text for k in ["冷蔵庫", "ﾚｲｿﾞｳｺ", "GRA600", "GRA500", "R27XN"]):
        return "refrigerator"
    if any(k in text for k in ["テレビ", "ﾃﾚﾋﾞ", "BRAVIA", "REGZA", "VIERA", "有機EL", "液晶テレビ", "XR70", "XR50"]):
        return "tv"
    if any(
        k in text
        for k in [
            "パソコン",
            "ﾊﾟｿｺﾝ",
            "ノートPC",
            "ﾉｰﾄﾊﾟｿｺﾝ",
            "SURFACE",
            "FMV",
            "EP2-",
            "K5I7",
            "83UQ",
        ]
    ):
        return "pc"
    if class_code:
        if class_code.startswith("31"):
            return "tv"
        if class_code.startswith("412"):
            return "pc"
    return None
