def upsert_master_and_kinohyo(session: Session, item: dict[str, Any]) -> tuple[Product, ProductKinohyo]:
    jan = str(item["jan_code"]).strip()
    model_no = str(item["search_model_no"]).strip()
    maker_code = item.get("maker_code") or _maker_code(jan)

    # 1. Check mst_product by jan_code or search_model_no (including hyphenless match)
    model_no_clean = model_no.replace("-", "")
    prod = session.scalar(
        select(Product).where(
            (Product.jan_code == jan)
            | (Product.search_model_no == model_no)
            | (Product.search_model_no == model_no_clean)
        )
    )
    price = int(item.get("edion_price") or 98000)
    shikiri = int(price / 1.1 * 0.72)

    input_data = {
        "kubun": "1",
        "effective_date": "2026-12-01",
        "class_code": item.get("class_code", "11000000"),
        "maker_name": item.get("maker_name", item["specs"].get("maker", "")),
        "maker_code": maker_code,
        "product_name": item.get("product_name", model_no),
        "maker_model_no": model_no,
        "edion_model_no": model_no,
        "features": item.get("features", ""),
        "jan_code": jan,
        "maker_price": str(item.get("maker_price", "オープン")),
        "shikiri_price": str(shikiri),
        "edion_price": str(price),
        "rank": "A1",
        "maker_warranty_months": "12",
        "long_warranty": str(item.get("long_warranty", "60")),
        "product_kubun": "家電",
        "order_unit": "1",
        "logistics_kubun": "1",
        "release_date": "2026-10-01",
        "expiry": "なし",
        "rec_comment_1": item.get("rec_comment_1", ""),
        "rec_comment_2": item.get("rec_comment_2", ""),
        "rec_comment_3": item.get("rec_comment_3", ""),
    }
    master_data = {
        "touroku_kubun": "1",
        "maker_code": maker_code,
        "maker_model_no": model_no,
        "search_model_no": model_no,
        "jan_code": jan,
        "effective_date": "20261201",
        "class_code": item.get("class_code", "11000000"),
        "maker_price": str(item.get("maker_price", "オープン")),
        "edion_price": str(price),
        "edion_display_price": str(price),
        "supplier_code": "C000900001",
        "order_unit": "1",
        "shikiri_price": str(shikiri),
        "net_cost": str(shikiri),
        "rank": "A1",
        "margin_kubun": "G",
        "maker_warranty_period": "012",
    }
    header_data = {
        "supplier_code": "900001",
        "company_name": f"{item.get('maker_name', 'メーカー')}販売株式会社",
        "contact_person": "営業担当",
        "md_owner": "田中",
        "registered_date": "2026-11-09",
        "product_group_name": item["category"],
        "tax_rate": "10%",
    }

    if prod is None:
        prod = Product(
            maker_code=maker_code,
            search_model_no=model_no,
            maker_model_no=model_no,
            jan_code=jan,
            class_code=item.get("class_code", "11000000"),
            product_name=item.get("product_name", model_no),
            maker_name=item.get("maker_name", item["specs"].get("maker", "")),
            effective_date="20261201",
            supplier_code="C000900001",
            master_data=master_data,
            input_data=input_data,
            header_data=header_data,
            updated_by="seed_kinohyo",
        )
        session.add(prod)
        session.flush()
        if item.get("long_warranty") and item["long_warranty"] not in ("対象外", "None"):
            session.add(
                Warranty(
                    product_id=prod.id,
                    data={
                        "kubun": "01",
                        "warranty_code": str(item["long_warranty"]),
                        "effective_date": "20261201",
                    },
                )
            )
    else:
        if not prod.product_name:
            prod.product_name = item.get("product_name", model_no)
        if not prod.maker_name:
            prod.maker_name = item.get("maker_name", item["specs"].get("maker", ""))

    # 2. Check mst_product_kinohyo
    kino = session.scalar(
        select(ProductKinohyo).where(
            (ProductKinohyo.jan_code == jan) | (ProductKinohyo.search_model_no == model_no)
        )
    )
    if kino is None:
        kino = ProductKinohyo(
            product_id=prod.id,
            jan_code=jan,
            search_model_no=model_no,
            category=item["category"],
            template_variant="auto",
            specs=item["specs"],
            ai_metadata={"seeded": True, "source": "機能表入力シート・標本マスタ"},
            updated_by="seed_kinohyo",
        )
        session.add(kino)
    else:
        kino.product_id = prod.id
        kino.category = item["category"]
        if not kino.specs:
            kino.specs = item["specs"]
        kino.updated_at = now_utc()

    return prod, kino


def seed_kinohyo_specs(session: Session) -> int:
    """Seeds all demo SKUs into mst_product and mst_product_kinohyo."""
    count = 0
    for item in DEMO_KINOHYO_ITEMS:
        upsert_master_and_kinohyo(session, item)
        count += 1
    session.commit()
    return count
